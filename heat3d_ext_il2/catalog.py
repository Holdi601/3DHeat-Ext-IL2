#: The viewer picks a stand-in figure from a unit's `type` word (fighter, bomber, attack...).
_TYPE_WORD = {"heavy fighter": "fighter", "reconnaissance": "bomber", "transport": "bomber transport",
              "glider": "bomber transport", "missile": "attack"}


def entry(folder: str, unit: str, game_name: str = "") -> dict:
    """The catalogue entry of one model folder: id, key, aliases (with the game's own name for it), class, nation,
    domain, type word."""
    base = unit.lstrip("_")
    row = TABLES.get(folder, {}).get(base)
    if row is None:
        key, cls, nation, aliases = base, FOLDER_CLASS.get(folder, "other"), "", []
    else:
        key, cls, nation, aliases = row
    aliases = [*aliases, *OTHER_NAMES.get(base, []), *([game_name] if game_name else [])]
    from .models import FOLDERS

    domain = FOLDERS.get(folder, "ground")
    # A folder name starting with "_" is a vehicle the player drives (Tank Crew): the same real vehicle as the AI
    # unit without it, its own unit of the data under its own object name.
    return {"id": unit, "folder": folder, "key": key, "gameName": game_name or key,
            "aliases": sorted(set(a for a in aliases if a != key)),
            "class": cls, "nation": nation, "domain": domain,
            "type": _TYPE_WORD.get(cls, cls), **({"drivable": True} if unit.startswith("_") else {})}


def safe_id(unit: str) -> str:
    return re.sub(r"[^a-z0-9_.-]", "_", unit.lower())
